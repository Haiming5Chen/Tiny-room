"""Write docs/CONTACT_PAIRS.md from materials/contact_pairs.py.

    python scripts/contact_pairs_doc.py          # rewrite the page
    python scripts/contact_pairs_doc.py --check  # exit 1 if the page is stale

The page is generated so it cannot drift from the numbers the simulator uses;
tests/test_contact_pairs.py runs the check.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))
from little_world.materials import contact_pairs as cp  # noqa: E402

PAGE = ROOT / "docs" / "CONTACT_PAIRS.md"


def render():
    lines = [
        "# Contact-pair friction",
        "",
        "Generated by `scripts/contact_pairs_doc.py` from `src/little_world/materials/contact_pairs.py`.",
        "Do not edit by hand; `tests/test_contact_pairs.py` fails when the two disagree.",
        "",
        "Friction is a property of a pair of surfaces. For every contact between two surfaces",
        "listed below, the MuJoCo adapter replaces MuJoCo's own combination (the larger of the",
        "two geoms' coefficients) with the pair's **kinetic** coefficient, after collision",
        "detection and before the solver (ADR 0010). Contacts between surfaces with no row",
        "keep MuJoCo's combination and count as unsourced.",
        "",
        "## Surfaces",
        "",
    ]
    lines += [f"- `{k}`: {v}" for k, v in sorted(cp.SURFACES.items())]
    lines += ["", "## Pairs", "", cp.markdown_table(), "",
              "Basis: *measured* = a primary measurement with stated conditions; *handbook* =",
              "an engineering compilation; *guideline* = a published design or cargo-securing",
              "value; *analogue* = no measurement of this pair was found, and the named similar",
              "pair's value is used. Analogues are always low confidence.", "",
              "## Conditions and spread", ""]
    for (a, b), p in sorted(cp.PAIRS.items()):
        lines.append(f"- **{a} / {b}** ({p.kinetic:.2f}): {p.note}")
    lines += ["", "## Sources", ""]
    for key, s in sorted(cp.SOURCES.items()):
        lines.append(f"- `{key}` - {s.citation}. <{s.url}> (read {s.checked})")
    lines += ["", "## Limits", "",
              "- MuJoCo has one sliding coefficient per contact; static values are recorded but",
              "  not simulated, so there is no stick-slip.",
              "- Elastomer friction falls as contact pressure rises; MuJoCo point contacts carry no",
              "  contact area, so rubber values are mid-range, not pressure-resolved.",
              "- Dry, clean, room temperature. Water, dust and temperature are not modelled yet.",
              "- Sources for the same nominal pair routinely differ by a factor of two; the notes",
              "  above give the spread behind each chosen value.", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        sys.exit(0 if PAGE.exists() and PAGE.read_text() == text else 1)
    PAGE.write_text(text)
    print(f"wrote {PAGE.relative_to(ROOT)}")
